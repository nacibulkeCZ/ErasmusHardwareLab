    private void SetLibraryInteractable(bool enabled)
    {
        for (int i = 0; i < allComponents.Count; i++)
        {
            var entry = allComponents[i];
            if (entry == null || entry.libraryWindowRoot == null)
                continue;

            var colliders = entry.libraryWindowRoot.GetComponentsInChildren<Collider>(true);
            for (int c = 0; c < colliders.Length; c++)
                colliders[c].enabled = enabled;

            var buttons = entry.libraryWindowRoot.GetComponentsInChildren<Button>(true);
            for (int b = 0; b < buttons.Length; b++)
                buttons[b].interactable = enabled;
        }
    }

    private void SetInspectRotationEnabled(Transform componentRoot, bool enabled)
    {
        if (componentRoot == null)
            return;

        var rotate = componentRoot.GetComponent<VRInspectRotate>();
        if (rotate == null)
            rotate = componentRoot.gameObject.AddComponent<VRInspectRotate>();

        rotate.referenceFrame = playerHead != null ? playerHead : (Camera.main != null ? Camera.main.transform : null);
        rotate.SetInspectEnabled(enabled);
    }

    private void SetComponentPhysicsAnimated(Transform componentRoot, bool asAnimated)
    {
        if (componentRoot == null)
            return;

        var bodies = componentRoot.GetComponentsInChildren<Rigidbody>(true);
        for (int i = 0; i < bodies.Length; i++)
        {
            bodies[i].isKinematic = asAnimated;
            bodies[i].useGravity = !asAnimated;
            if (asAnimated)
            {
                bodies[i].linearVelocity = Vector3.zero;
                bodies[i].angularVelocity = Vector3.zero;
            }
        }
    }

    private void SetMovementLocked(bool locked)
    {
        if (locked)
        {
            runtimeDisabledMovementBehaviours.Clear();

            for (int i = 0; i < movementBehavioursToDisable.Count; i++)
            {
                Behaviour behaviour = movementBehavioursToDisable[i];
                if (behaviour == null || !behaviour.enabled)
                    continue;

                behaviour.enabled = false;
                runtimeDisabledMovementBehaviours.Add(behaviour);
            }

            HandLocomotionJoystick[] joystickLocomotion = FindObjectsByType<HandLocomotionJoystick>(FindObjectsSortMode.None);
            for (int i = 0; i < joystickLocomotion.Length; i++)
            {
                if (joystickLocomotion[i] == null || !joystickLocomotion[i].enabled)
                    continue;

                joystickLocomotion[i].enabled = false;
                runtimeDisabledMovementBehaviours.Add(joystickLocomotion[i]);
            }

            return;
        }

        for (int i = 0; i < runtimeDisabledMovementBehaviours.Count; i++)
        {
            Behaviour behaviour = runtimeDisabledMovementBehaviours[i];
            if (behaviour != null)
                behaviour.enabled = true;
        }

        runtimeDisabledMovementBehaviours.Clear();
    }

    private IEnumerator AnimateCaseDoorFlyAway()
    {
        if (pcCaseDoorObject == null)
            yield break;

        pcCaseDoorObject.gameObject.SetActive(true);
        SetComponentPhysicsAnimated(pcCaseDoorObject, true);

        Vector3 reference = GetReferencePosition();
        Vector3 dir = (pcCaseDoorObject.position - reference).normalized;
        if (dir.sqrMagnitude < 0.01f)
            dir = transform.right;

        Vector3 targetPos = pcCaseDoorObject.position + dir * caseDoorFlyDistance + Vector3.up * caseDoorFlyUpOffset;
        Quaternion targetRot = pcCaseDoorObject.rotation * Quaternion.Euler(0f, caseDoorFlyRotateDegrees, 0f);

        yield return StartCoroutine(AnimateTransform(
            pcCaseDoorObject,
            targetPos,
            targetRot,
            pcCaseDoorObject.localScale,
            caseDoorFlyDuration));

        if (hideCaseDoorAfterFly)
            pcCaseDoorObject.gameObject.SetActive(false);
    }

    private void RestoreCaseDoorState()
    {
        if (!hasDoorPose || pcCaseDoorObject == null)
            return;

        pcCaseDoorObject.gameObject.SetActive(doorPose.active);
        pcCaseDoorObject.position = doorPose.position;
        pcCaseDoorObject.rotation = doorPose.rotation;
    }

    private void OnValidate()
    {
        if (hiddenScaleMultiplier < 0.01f)
            hiddenScaleMultiplier = 0.01f;

        if (inspectScaleMultiplier < 0.1f)
            inspectScaleMultiplier = 0.1f;

        if (moveDuration < 0f)
            moveDuration = 0f;

        if (caseDoorFlyDuration < 0f)
            caseDoorFlyDuration = 0f;

        if (libraryRadius < 0.2f)
            libraryRadius = 0.2f;

        if (libraryArcDegrees < 1f)
            libraryArcDegrees = 1f;

        if (revealDistanceFromCase < 0.05f)
            revealDistanceFromCase = 0.05f;

        if (placeholderWindowDepth < 0.005f)
            placeholderWindowDepth = 0.005f;

        placeholderWindowSize.x = Mathf.Max(0.05f, placeholderWindowSize.x);
        placeholderWindowSize.y = Mathf.Max(0.05f, placeholderWindowSize.y);

        if (libraryForwardOffset < 0.1f)
            libraryForwardOffset = 0.1f;

        if (hiddenItemsForwardDistance < 0.1f)
            hiddenItemsForwardDistance = 0.1f;
    }
